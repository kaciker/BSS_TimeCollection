export function getLanguage(): Language {
  const value = localStorage.getItem(STORAGE_KEY);
  return value === "fr" || value === "es" || value === "pl" ? value : "en";
}

export function setLanguage(value: Language): void {
  localStorage.setItem(STORAGE_KEY, value);
  document.documentElement.lang = value;
  window.dispatchEvent(new Event(EVENT_NAME));
}

export function translate(language: Language, key: string): string {
  return strings[language][key] ?? extra[language][key] ?? strings.en[key] ?? extra.en[key] ?? key;
}

export function translateTerminalError(language: Language, message: string): string {
  const presence = message.match(/^External perimeter presence:\s*(UNKNOWN|OUTSIDE|STALE|ERROR)$/i);
  if (!presence) return message;
  return translate(language, `externalPerimeterPresence${presence[1].toUpperCase()}`);
}

export function useLanguage() {
  const [language, setCurrent] = useState<Language>(getLanguage);
  useEffect(() => {
    document.documentElement.lang = language;
    const changed = () => setCurrent(getLanguage());
    window.addEventListener(EVENT_NAME, changed);
    return () => window.removeEventListener(EVENT_NAME, changed);
  }, [language]);
  return { language, setLanguage, t: (key: string) => translate(language, key) };
}
